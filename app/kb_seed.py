def seed_kb(conn: sqlite3.Connection) -> None:
    """Заполняет базу знаний начальными данными"""
    for code, data in KB_SEED.items():
        upsert_kb_article(
            conn,
            code,
            data["title"],
            data.get("desc", ""),
            data.get("rec", "")
        )