# Обратный словарь для отладки
CANONICAL_TO_ADDRS: Dict[str, list] = {}
for addr, key in ADDR_TO_CANONICAL.items():
    if key not in CANONICAL_TO_ADDRS:
        CANONICAL_TO_ADDRS[key] = []
    CANONICAL_TO_ADDRS[key].append(addr)


def get_canonical_key(addr: int, name: str = "") -> Optional[str]:
    """
    Получить канонический ключ по адресу регистра
    """
    # Сначала проверяем по адресу
    if addr in ADDR_TO_CANONICAL:
        return ADDR_TO_CANONICAL[addr]

    # Если адрес не найден, пробуем по названию
    n = name.lower() if name else ""

    # Мощности
    if "квт" in n or "kw" in n:
        if "l1" in n:
            return "Активная мощность L1"
        elif "l2" in n:
            return "Активная мощность L2"
        elif "l3" in n:
            return "Активная мощность L3"
        return "Активная мощность"

    if "квар" in n or "kvar" in n:
        if "l1" in n:
            return "Реактивная мощность L1"
        elif "l2" in n:
            return "Реактивная мощность L2"
        elif "l3" in n:
            return "Реактивная мощность L3"
        return "Реактивная мощность"

    if "ква" in n or "kva" in n:
        if "l1" in n:
            return "Полная мощность L1"
        elif "l2" in n:
            return "Полная мощность L2"
        elif "l3" in n:
            return "Полная мощность L3"
        return "Полная мощность"

    # Напряжения
    if "напряж" in n:
        if "l1-l2" in n or "l1l2" in n:
            return "Напряжение L1-L2"
        elif "l2-l3" in n or "l2l3" in n:
            return "Напряжение L2-L3"
        elif "l3-l1" in n or "l3l1" in n:
            return "Напряжение L3-L1"

    # Сила сигнала
    if "сила сигнала" in n or "signal" in n:
        return "Сила сигнала 4G"

    # Моточасы и ТО
    if "моточас" in n or "наработк" in n:
        return "Моточасы"
    if "таймер" in n and "техобслуж 1" in n:
        return "Таймер ТО-1"
    if "таймер" in n and "техобслуж 2" in n:
        return "Таймер ТО-2"
    if "таймер" in n and "техобслуж 3" in n:
        return "Таймер ТО-3"

    return None


