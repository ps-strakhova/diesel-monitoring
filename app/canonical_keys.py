def get_canonical_key(addr: int, name: str = "") -> Optional[str]:
    """
    Получить канонический ключ по адресу регистра или названию
    """
    # Сначала проверяем по адресу
    if addr in ADDR_TO_CANONICAL:
        return ADDR_TO_CANONICAL[addr]

    # Если адрес не найден, пробуем по названию
    if not name:
        return None

    n = name.lower()

    for keywords, mapping in KEYWORD_MAPPINGS:
        if any(k in n for k in keywords):
            # Проверяем специфичные варианты
            for key, value in mapping.items():
                if key != "default" and key in n:
                    return value
            # Возвращаем дефолтный
            return mapping.get("default")

    return None